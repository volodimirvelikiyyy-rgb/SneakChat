_HYPHEN_OR_DIGIT_BEFORE = re.compile(r"[-\d]\s*$")


def _absent_hit(message: str, phrases) -> bool:
    """Есть ли в тексте целая формулировка свойства, не входящая в составное слово."""
    lowered = message.strip().lower()
    for phrase in phrases:
        for found in _alias_pattern(phrase).finditer(lowered):
            if _HYPHEN_OR_DIGIT_BEFORE.search(lowered[: found.start()]):
                continue
            return True
    return False


