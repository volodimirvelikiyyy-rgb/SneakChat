_ALIAS_PATTERN_CACHE: dict[str, "re.Pattern[str]"] = {}
_VALUE_PATTERN_CACHE: dict[str, "re.Pattern[str]"] = {}


def _alias_pattern(alias: str) -> "re.Pattern[str]":
    """Строгий образец: алиас обязан совпасть с целым токеном или целой объявленной фразой.

    Генерации словоформ здесь нет: допустимые формы перечислены в словарях явно. Поэтому
    «парные» не становится Men, «залью» — Training, «коричный» — Brown, а «красную» и
    «для трейла» работают, потому что объявлены.
    """
    if alias not in _ALIAS_PATTERN_CACHE:
        _ALIAS_PATTERN_CACHE[alias] = re.compile(
            rf"(?<![а-яёa-zіїєґ0-9-]){re.escape(alias)}(?![а-яёa-zіїєґ0-9-])"
        )
    return _ALIAS_PATTERN_CACHE[alias]


def _value_pattern(alias: str) -> "re.Pattern[str]":
    """Мягкий образец — только для канонизации уже выделенного значения модели.

    Здесь вход — отдельное значение («бел», «сер»), а не живая фраза, поэтому совпадение с
    началом слова допустимо. Для поиска подстрок в пользовательском тексте он не применяется.
    """
    if alias not in _VALUE_PATTERN_CACHE:
        _VALUE_PATTERN_CACHE[alias] = re.compile(rf"(?<![а-яёa-zіїєґ0-9]){re.escape(alias)}")
    return _VALUE_PATTERN_CACHE[alias]


def match_alias(text: str, aliases: dict[str, str]) -> str | None:
    """Значение по первому совпавшему алиасу, начиная с самого длинного.

    Длинный алиас важнее короткого: «серебристые» — это `Silver`, а не `Grey`
    (короткий «сер» иначе перехватывает слово). Совпадение считается только с начала
    слова, поэтому «беж» не превращает «пробежку» в бежевый цвет.
    """
    lowered = text.strip().lower()
    for alias in sorted(aliases, key=len, reverse=True):
        if _alias_pattern(alias).search(lowered):
            return aliases[alias]
    return None


