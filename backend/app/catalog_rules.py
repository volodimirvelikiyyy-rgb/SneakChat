def detect_out_of_range_size(message: str) -> float | None:
    """Размер, который пользователь назвал, но которого у каталога быть не может («размер 99»).

    Такой размер нельзя ни применить (в каталоге его нет), ни молча выбросить: тогда
    пользователь получил бы ответ на другой вопрос. Ценовые выражения вырезаются заранее,
    поэтому «до 150» остаётся бюджетом, а не невозможным размером, а голое число считается
    размером только если это всё сообщение — так отвечают на вопрос о размере.
    """
    # Локальный импорт: `services.assistant` сам импортирует этот модуль, а вырезание
    # ценовых выражений живёт рядом с ценовыми шаблонами.
    from .services.assistant import _strip_price_expressions

    lowered = size_context_mask(message).lower().replace(",", ".")
    stripped = _strip_price_expressions(lowered)
    minimum, maximum = size_axis_bounds()
    for match in re.finditer(r"(?:размер[а-яё]*|розмір[а-яіїєґ]*|size)\s*[:\s.]*(\d{2,3}(?:\.\d)?)", stripped):
        size = float(match.group(1))
        if not minimum <= size <= maximum:
            return size
    bare = stripped.strip().strip("!?. ")
    if re.fullmatch(r"\d{2,3}(?:\.\d)?", bare):
        size = float(bare)
        if not minimum <= size <= maximum:
            return size
    return None




def lexicon() -> str:
    """Лексикон каталога для промпта: канонические значения и то, как их пишут пользователи.

    Собирается из тех же словарей, что использует детерминированный парсер, поэтому модель
    и парсер опираются на один словарь, а не на два расходящихся списка.
    """
    lines = [
        "Catalog vocabulary. Return only these canonical values:",
        f"brands: {', '.join(BRAND_VALUES.values())}",
        f"colors: {', '.join(COLOR_VALUES.values())}",
        f"gender: {', '.join(GENDER_VALUES)}",
        f"use_case: {', '.join(USE_CASE_VALUES)}",
        f"feature: {', '.join(FEATURE_VALUES)}",
        f"size: JSON number between {MIN_SIZE:g} and {MAX_SIZE:g}",
        "How users word these values (Russian / Ukrainian / English):",
    ]
    for title, aliases in (("colors", COLOR_ALIASES), ("use_case", USE_CASE_ALIASES), ("feature", FEATURE_ALIASES)):
        lines.append(f"- {title}: " + "; ".join(f"{value} = {'/'.join(words)}" for value, words in aliases.items()))
    lines.append("- brands may be typed in Cyrillic or with typos: найк, адидас, адики, пума, асикс, нью баланс.")
    return "\n".join(lines)


