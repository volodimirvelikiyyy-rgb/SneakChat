def implied_value(key: str, phrase: str) -> str | None:
    """Какое значение словарь приписывает этой формулировке (None — словарь её не знает)."""
    aliases = FILTER_ALIAS_MAPS.get(key)
    if not aliases:
        return None
    return match_alias(phrase, aliases)


def match_value(text: str, aliases: dict[str, str]) -> str | None:
    """Значение по алиасу для отдельного значения модели (мягкий путь B)."""
    lowered = text.strip().lower()
    for alias in sorted(aliases, key=len, reverse=True):
        if _value_pattern(alias).search(lowered):
            return aliases[alias]
    return None


def alias_owners(phrase: str) -> set[str]:
    """Каким фильтрам словарь уже присваивает эту формулировку.

    Нужно, чтобы подтверждение от модели не переносило признак на чужой фильтр:
    «белые» в словаре относятся к цвету и не могут подтверждать бренд или пол.
    """
    normalized = phrase.strip().lower()
    owners = set()
    for key, aliases in (
        ("brand", BRAND_CANONICAL),
        ("color", COLOR_CANONICAL),
        ("use_case", USE_CASE_ALIAS_MAP),
        ("feature", FEATURE_ALIAS_MAP),
    ):
        if any(_alias_pattern(alias).search(normalized) for alias in aliases):
            owners.add(key)
    return owners


# --- отрицания --------------------------------------------------------------
# «не Nike», «только не белые», «не для бега», «без белого», «кроме Nike».
# Маркер — отдельное слово, поэтому «недорого» и «непромокаемые» отрицанием не являются.
NEGATION_MARKERS = ("не", "кроме", "крім", "без")
# Сколько слов после маркера считается его областью действия.
NEGATION_WINDOW = 3
# Между отрицанием и значением могут стоять только служебные слова: «не для бега», «не в школу».
# Если между ними оказалось содержательное слово, отрицание относится к нему, а не к значению:
# «чтобы не промокали на осень» — это запрос свойства, а не отказ от осени.
NEGATION_LEAD_WORDS = frozenset({
    # Предлоги и союзы: «не для бега», «не в школу», «без белого».
    "для", "на", "в", "во", "с", "со", "за", "по", "под", "до", "из", "от", "к", "ко",
    "кроме", "крім", "без", "не", "и", "а", "та",
    # Глаголы предпочтения: «не хочу чёрные» — значение стоит сразу за ними.
    # «не нужны» и подобные фразы отказа сюда не входят: они разбираются отдельно как отказ
    # от значения, стоящего перед ними, иначе «чёрные не нужны 43» потеряло бы размер.
    "хочу", "хочется", "хочет", "хочемо", "беру", "возьму", "люблю", "предпочитаю",
})
# Слова-сомнения: «не знаю, для бега или для зала» — это не отказ от бега.
NEGATION_SKIP_WORDS = ("знаю", "знаешь", "уверен", "уверена", "помню", "понимаю", "понял", "вирішив", "решил")
# Отказ, стоящий после значения: «белые не нужны», «для бега не подходит».
# Допустимое окончание слова после алиаса: «бег» в «бега», «белые» в «белых».
NEGATION_ENDING_LIMIT = 3
NEGATION_POST_MARKERS = frozenset({
    "не нужны", "не нужен", "не нужна", "не нужно", "не надо", "не подходит", "не подходят",
    "не интересует", "не интересуют", "не нравится", "не хочу", "не беру",
    "не потрібні", "не потрібен", "не підходить", "не цікавить", "не хочу",
})
# Ценовые слова: «не дороже 43» — это бюджет, а не исключение размера.
NEGATION_PRICE_GUARD = (
    "дороже", "дорожче", "дешевле", "дешевше", "до", "від", "от", "за", "бюджет", "цена", "ціна",
    "лимит", "ліміт", "максимум", "стоит", "коштує", "$", "€", "грн", "руб", "долл",
)


def _negatable(aliases: dict[str, tuple[str, ...]], values: dict[str, str]) -> dict[str, str]:
    """Словарь «алиас → каноническое значение» без алиасов, которые сами содержат отрицание.

    «не промокают» — это запрос свойства, а не отказ от него, поэтому алиас «не промок»
    отрицать словом «не» нельзя: такие алиасы из словаря отрицаний исключаются.
    """
    mapping = {value.lower(): values[value] for value in aliases if value in values}
    for value, words in aliases.items():
        for word in words:
            if word.startswith("не") or " не" in word:
                continue
            mapping[word] = values[value]
    return mapping


NEGATION_ALIAS_MAPS: dict[str, dict[str, str]] = {
    # Бренд хранится строкой, поэтому перечисленные бренды и их алиасы — один словарь.
    "brand": dict(BRAND_CANONICAL),
    "color": _negatable(COLOR_ALIASES, COLOR_VALUES),
    "use_case": _negatable(USE_CASE_ALIASES, {value: value for value in USE_CASE_VALUES}),
    "feature": _negatable(FEATURE_ALIASES, {value: value for value in FEATURE_VALUES}),
    "gender": _negatable(GENDER_ALIASES, {value: value for value in GENDER_VALUES}),
}

_CLAUSE_SPLIT = re.compile(r"[.,;:!?\n]+")
_NEGATED_SIZE = re.compile(r"(?<!\d)(\d{2}(?:\.\d)?)(?!\d)")


def _negation_clauses(message: str) -> list[tuple[str, int]]:
    """Куски сообщения между знаками препинания вместе со смещением в исходном тексте.

    Область действия «не» не выходит за знак препинания: «это не важно. Покажи белые» —
    это два разных куска, и отрицание относится только к первому.
    """
    clauses = []
    for found in re.finditer(r"[^.,;:!?\n]+", message.lower()):
        if found.group(0).strip():
            clauses.append((found.group(0), found.start()))
    return clauses


def _alias_span(aliases: dict[str, str], text: str) -> tuple[int, int] | None:
    """Самый ранний совпавший алиас: позиции начала и конца (None — совпадений нет)."""
    best: tuple[int, int] | None = None
    for alias in aliases:
        found = _alias_pattern(alias).search(text)
        if found is not None and (best is None or found.start() < best[0]):
            best = (found.start(), found.end())
    return best


def _alias_end_span(aliases: dict[str, str], text: str) -> tuple[int, int] | None:
    """Совпавший алиас, который заканчивается позже всех: значение стоит в конце фразы."""
    best: tuple[int, int] | None = None
    for alias in aliases:
        found = _alias_pattern(alias).search(text)
        if found is not None and (best is None or found.end() > best[1]):
            best = (found.start(), found.end())
    return best


def _word_index_of(text: str, position: int) -> int:
    """Индекс слова, в которое попадает позиция символа."""
    return text[:position].count(" ")


def _negation_value(words: list[str], start: int) -> tuple[str, object, int] | None:
    """Значение, которое отрицает маркер на позиции `start`, и последнее слово этого значения.

    Значение должно начинаться сразу за маркером или за служебными словами после него.
    Поиск идёт от самого маркера к более далёким словам, поэтому «не для бега» даёт бег,
    а «не промокали на осень» не даёт ничего: между «не» и «осень» стоит содержательное слово.
    Возвращается ещё и граница значения, чтобы парсер мог вырезать ровно его, а не всю фразу.
    """
    for offset in range(NEGATION_WINDOW):
        prefix = words[start + 1: start + 1 + offset]
        if not all(word in NEGATION_LEAD_WORDS for word in prefix):
            break
        window = words[start + 1 + offset: start + 1 + offset + NEGATION_WINDOW]
        if not window:
            break
        text = " ".join(window)
        for axis, aliases in NEGATION_ALIAS_MAPS.items():
            # Совпадение обязано начинаться с первого слова окна: иначе это значение другой
            # части фразы, а не то, которое отрицает маркер.
            span = _alias_span(aliases, text)
            if span is not None and span[0] == 0:
                last_word = start + 1 + offset + _word_index_of(text, span[1] - 1)
                return axis, match_alias(text, aliases), last_word
        if not any(word in NEGATION_PRICE_GUARD for word in window):
            # Размер — это число: «не 43». Ценовое слово в окне означает бюджет
            # («не дороже 43»), поэтому тогда размер не исключается.
            size_match = _NEGATED_SIZE.match(text)
            if size_match:
                size = float(size_match.group(1))
                if MIN_SIZE <= size <= MAX_SIZE:
                    last_word = start + 1 + offset + _word_index_of(text, size_match.end() - 1)
                    return "size", size, last_word
    return None


def _post_negation_hits(words: list[str]) -> list[tuple[str, object, int, int]]:
    """Отрицание после значения: «белые не нужны», «для бега не подходит».

    Маркер стоит не перед значением, а после него, поэтому значение ищется в словах перед
    фразой отказа — с тем же правилом: между значением и отказом только служебные слова.
    """
    hits: list[tuple[str, object, int, int]] = []
    for index in range(len(words)):
        rejection_end = None
        for size in (3, 2):
            phrase = words[index: index + size]
            if " ".join(phrase) in NEGATION_POST_MARKERS:
                rejection_end = index + len(phrase) - 1
                break
        if rejection_end is None:
            continue
        for back in range(1, NEGATION_WINDOW):
            start = index - back
            if start < 0:
                break
            prefix = words[start: index - 1]
            if not all(word in NEGATION_LEAD_WORDS for word in prefix):
                break
            text = " ".join(words[start:index])
            matched = False
            for axis, aliases in NEGATION_ALIAS_MAPS.items():
                span = _alias_end_span(aliases, text)
                # Значение должно заканчивать фразу перед отказом: «белые не нужны», а не
                # «белые кроссовки не нужны». Короткое окончание слова допускается: «бега».
                if span is not None and span[1] >= len(text) - NEGATION_ENDING_LIMIT:
                    hits.append((axis, match_alias(text, aliases), start, rejection_end))
                    matched = True
                    break
            if not matched:
                # Размер — это число: «43 не нужен». Ценовые слова рядом означают бюджет,
                # поэтому «100 не дороже» размером не считается.
                size_match = _NEGATED_SIZE.fullmatch(text)
                if size_match and not any(word in NEGATION_PRICE_GUARD for word in words[start:index]):
                    size = float(size_match.group(1))
                    if MIN_SIZE <= size <= MAX_SIZE:
                        hits.append(("size", size, start, rejection_end))
                        matched = True
            if not matched:
                continue
            break
    return hits


def _negation_hits(words: list[str]) -> list[tuple[str, object, int, int]]:
    """Все отрицания фразы: маркер перед значением и фраза отказа после него."""
    hits: list[tuple[str, object, int, int]] = []
    for index, word in enumerate(words):
        if word not in NEGATION_MARKERS:
            continue
        window = words[index + 1: index + 1 + NEGATION_WINDOW]
        if not window or any(item in NEGATION_SKIP_WORDS for item in window):
            continue
        found = _negation_value(words, index)
        if found is not None:
            axis, value, last_word = found
            hits.append((axis, value, index, last_word))
    return hits + _post_negation_hits(words)


def _clause_words(clause: str) -> tuple[list[str], list[int]]:
    """Слова куска сообщения и позиция каждого слова в этом куске."""
    matches = list(re.finditer(r"\S+", clause))
    return [match.group(0) for match in matches], [match.start() for match in matches]


def negation_mask(message: str) -> str:
    """Текст, в котором исключённые значения вырезаны.

    Нужен положительному разбору: «только не Nike» не должно превратиться в фильтр по бренду
    Nike. Значение, названное и вне отрицания, остаётся — тогда это настоящее противоречие,
    и о нём сообщают отдельно.
    """
    lowered = message.lower().replace(",", ".")
    masked = list(message)
    for clause, offset in _negation_clauses(lowered):
        words, starts = _clause_words(clause)
        for _axis, _value, first_word, last_word in _negation_hits(words):
            end = starts[last_word] + len(words[last_word])
            for position in range(offset + starts[first_word], min(offset + end, len(masked))):
                masked[position] = " "
    return "".join(masked)


def detect_negations(message: str) -> dict[str, list[str]]:
    """Какие значения пользователь исключил: «не Nike», «только не белые», «не для бега».

    Отрицание — такое же условие, как и положительное: молча его игнорировать нельзя,
    иначе пользователю покажут именно то, что он просил не показывать.
    """
    excluded: dict[str, list[str]] = {}
    for clause, _offset in _negation_clauses(message.lower().replace(",", ".")):
        words, _starts = _clause_words(clause)
        for axis, value, _first_word, _last_word in _negation_hits(words):
            if value is not None and value not in excluded.setdefault(axis, []):
                excluded[axis].append(value)
    return excluded


