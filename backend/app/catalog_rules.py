def strict_phrase_hits(message: str, phrases) -> bool:
    """Есть ли в тексте целая объявленная формулировка (без совпадений внутри слов)."""
    lowered = message.strip().lower()
    return any(_alias_pattern(phrase).search(lowered) for phrase in phrases)


def _phrase_hits(message: str, phrases) -> bool:
    return any(phrase in message for phrase in phrases)


def detect_removals(message: str) -> set[str]:
    """Какие условия пользователь просит снять («бренд не важен», «покажи все»)."""
    lowered = message.lower()
    removed = {key for key, phrases in REMOVAL_PHRASES.items() if _phrase_hits(lowered, phrases)}
    if _phrase_hits(lowered, REMOVAL_MARKERS):
        # «размер не учитывай», «цену не учитывай», «любой бренд» — форм слишком много,
        # поэтому ловим по паре «ключевое слово условия + маркер отказа».
        removed.update(
            key for key, subjects in REMOVAL_SUBJECTS.items() if any(subject in lowered for subject in subjects)
        )
    if _phrase_hits(lowered, REMOVE_ALL_PHRASES):
        removed.update({"brand", "color", "size", "price"})
        removed.add("all")
    if "не обязательно" in lowered or "не обов" in lowered:
        # «не обязательно Nike» — снимаем бренд, если в сообщении назван бренд.
        if match_alias(lowered, BRAND_CANONICAL):
            removed.add("brand")
    return removed


