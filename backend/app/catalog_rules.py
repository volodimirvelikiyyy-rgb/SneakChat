# Возраст человека в сообщении. Правило контекстное и узкое: признак возраста стоит либо
# непосредственно перед числом («мне 43», «мені 43 роки»), либо сразу после него («43 года»).
# Так «мне 43 года» и «43 роки» не становятся размером, а «43» в ответ на вопрос о размере —
# становится. Общий разбор смысла здесь не нужен и не делается.
AGE_MARKERS_BEFORE = ("мне", "мені", "возраст", "вік")
AGE_MARKERS_AFTER = ("лет", "год", "года", "году", "років", "роки", "рік", "року")
# Слова-единицы после числа: «43 пары» — это количество, а не размер.
QUANTITY_UNIT_STEMS = ("пар", "шт", "штук", "литр", "літр", "миллилитр", "мілілітр", "сантиметр",
                       "килограмм", "кілограм", "грамм", "метр", "упаков", "градус", "унци", "тонн", "комплект", "короб", "недел", "месяц", "місяц", "кг", "км", "см",
                       "мм", "мл", "минут", "час", "дн", "год", "лет", "рок", "процент", "літр", "тижн")
# Однобуквенные единицы — только точным совпадением: иначе «43 модель» станет количеством.
QUANTITY_UNIT_EXACT = ("м", "г", "л")
_AGE_NUMBER = re.compile(r"(?<![а-яёa-zіїєґ])(\d{1,3})(?![0-9])")


def _number_context(message: str, position_start: int, position_end: int) -> tuple[list[str], list[str]]:
    """Слова перед числом и после него."""
    lowered = message.lower()
    return lowered[:position_start].split(), [word.strip(".,!?;:") for word in lowered[position_end:].split()]


SIZE_WORDS = ("размер", "розмір", "size")


def _named_as_size(before: list[str], after: list[str] | None = None) -> bool:
    """Число названо размером словом — тогда оно размер, а не возраст и не количество.

    Слово может стоять и перед числом («размер 43»), и после него («43 размер»).
    """
    before_says = bool(before) and any(before[-1].startswith(word) or before[-1] == word for word in SIZE_WORDS)
    after_says = bool(after) and any(after[0].startswith(word) or after[0] == word for word in SIZE_WORDS)
    return before_says or after_says


def age_spans(message: str) -> list[tuple[int, int]]:
    """Вхождения чисел, которые означают возраст.

    Возвращаются именно вхождения, а не значения: в «мне 43 года, размер 43» возраст только
    первое число. Второе названо словом «размер» и размером быть обязано.
    """
    spans: list[tuple[int, int]] = []
    for match in _AGE_NUMBER.finditer(message.lower()):
        before, after = _number_context(message, match.start(), match.end())
        if _named_as_size(before, after):
            continue
        if before and before[-1] in AGE_MARKERS_BEFORE:
            spans.append((match.start(), match.end()))
        elif after and after[0].lstrip("-").startswith(AGE_MARKERS_AFTER):
            spans.append((match.start(), match.end()))
    return spans


def age_numbers(message: str) -> set[float]:
    """Значения чисел, которые в этом сообщении означают возраст."""
    return {float(message[start:end]) for start, end in age_spans(message)}


def quantity_spans(message: str) -> list[tuple[int, int]]:
    """Вхождения чисел, которые считают что-то, а не выбирают размер: «43 пары», «43 штуки»."""
    spans: list[tuple[int, int]] = []
    for match in _AGE_NUMBER.finditer(message.lower()):
        before, after = _number_context(message, match.start(), match.end())
        if _named_as_size(before, after):
            continue
        if after and (after[0].startswith(QUANTITY_UNIT_STEMS) or after[0] in QUANTITY_UNIT_EXACT):
            spans.append((match.start(), match.end()))
    return spans


def size_named_numbers(message: str) -> set[float]:
    """Числа, которые названы размером словом: «размер 43»."""
    named = set()
    for match in _AGE_NUMBER.finditer(message.lower()):
        before, after = _number_context(message, match.start(), match.end())
        if _named_as_size(before, after):
            named.add(float(match.group(1)))
    return named


def excluded_size_numbers(message: str) -> set[float]:
    """Числа, которые размером не являются: возраст и количество.

    Число, названное размером словом, исключением не становится: в «мне 43 года, размер 43»
    возраст и размер совпадают по значению, но пользователь назвал размер прямо.
    """
    spans = age_spans(message) + quantity_spans(message)
    return {float(message[start:end]) for start, end in spans} - size_named_numbers(message)


def size_context_mask(message: str) -> str:
    """Текст без чисел-возрастов и чисел-количеств: разбор размера их не увидит."""
    spans = age_spans(message) + quantity_spans(message)
    # Centimetres and manufacturer CM/JP are measurements, never EU sizes.
    spans += [match.span(1) for match in re.finditer(
        r"(?<![\w.])(\d+(?:[.,]\d+)?)\s*(?:см|cm|jp)\b", message, re.IGNORECASE
    )]
    spans += [match.span(1) for match in re.finditer(
        r"\b(?:cm(?:/jp)?|jp)\s*[:=]?\s*(\d+(?:[.,]\d+)?)", message, re.IGNORECASE
    )]
    if not spans:
        return message
    masked = list(message)
    for start, end in spans:
        for position in range(start, min(end, len(masked))):
            masked[position] = " "
    return "".join(masked)


def age_mask(message: str) -> str:
    """Текст без возрастных чисел: положительный разбор их не видит."""
    masked = list(message)
    ages = age_numbers(message)
    if not ages:
        return message
    for match in _AGE_NUMBER.finditer(message.lower()):
        if float(match.group(1)) not in ages:
            continue
        for position in range(match.start(), min(match.end(), len(masked))):
            masked[position] = " "
    return "".join(masked)
