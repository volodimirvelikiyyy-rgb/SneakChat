def product_fact_question(message: str) -> set[str]:
    """Recognize questions about catalog fields, not field values or model names.

    Numbers, brands and other content words leave the turn to the normal parser.
    The same noun/verb rules cover single and combined RU/UK fact questions.
    """
    words = re.findall(r"[\w’'-]+", message.casefold())
    patterns = {
        "price": r"цен(?:а|ы|е|у|ой)?|цін(?:а|и|і|у)?|стоимость|вартість|стоит|стоят|коштує|коштують",
        "size": r"размер(?:ы|а|у|е|ов|ом)?|розмір(?:и|ів|у|і|ом)?",
        "availability": r"наличи(?:е|и|я)|наявн(?:ість|ості)|остат(?:ок|ки|ков)|залиш(?:ок|ки|ків)|есть|є",
    }
    fillers = set(FUNCTION_WORDS) | {"сколько", "скільки", "мой", "мій", "моего", "мого", "этих", "цих",
                                     "які", "який", "яка", "яку", "яких", "якого", "що", "какого", "каких",
                                     "узнать", "дізнатися", "проверить", "перевірити", "скажи", "скажіть",
                                     "подскажите", "підкажіть", "підкажи", "eu"}
    fields = set()
    if any(word in {"не", "ні", "без"} for word in words):
        return fields
    for word in words:
        matched = {field for field, pattern in patterns.items() if re.fullmatch(pattern, word)}
        if not matched and word not in fillers:
            return set()
        fields.update(matched)
    return fields


